function buildJob(seed: JobSeed): Job {
  const company = companyOf(seed.company);
  const employer = employerByCompanySlug[seed.company];
  if (!employer) throw new Error(`No employer for company ${seed.company}`);

  const published = seed.status === 'DRAFT' ? undefined : hoursAgo(seed.postedHoursAgo);

  return {
    id: `job_${seed.slug}`,
    slug: seed.slug,
    title: seed.title,
    employer: employer.user,
    company: {
      id: company.id,
      name: company.name,
      slug: company.slug,
      type: company.type,
      verification: company.verification,
    },
    category: categoryOf(seed.category),
    skills: seed.skills.map(skillOf),
    description: seed.description,
    workersRequired: seed.required,
    hiredCount: seed.hired,
    vacanciesLeft: Math.max(seed.required - seed.hired, 0),
    location: placeOf(seed.city, seed.locality),
    startDate: daysAhead(seed.startInDays),
    endDate: daysAhead(seed.startInDays + seed.durationDays),
    durationDays: seed.durationDays,
    shift: seed.shift,
    workingHours: seed.hours,
    salary: { amount: seed.salary, type: seed.salaryType, negotiable: seed.negotiable },
    perks: seed.perks,
    experienceRequiredYears: seed.experience,
    urgency: seed.urgency,
    contactPreference: 'IN_APP',
    status: seed.status,
    ...(published ? { publishedAt: published } : {}),
    expiresAt: daysAhead(seed.startInDays + seed.durationDays + 15),
    viewCount: seed.views,
    applicationCount: seed.applications,
    createdAt: hoursAgo(seed.postedHoursAgo + 1),
    updatedAt: hoursAgo(Math.max(seed.postedHoursAgo - 2, 1)),
  };
}

export const jobs: Job[] = JOB_SEEDS.map(buildJob);

export const jobBySlug: Record<string, Job> = Object.fromEntries(
  jobs.map((job) => [job.slug, job]),
);

export function jobOf(slug: string): Job {
  const job = jobBySlug[slug];
  if (!job) throw new Error(`Unknown job slug in demo data: ${slug}`);
  return job;
}

