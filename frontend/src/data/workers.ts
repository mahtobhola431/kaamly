/** Profile completion is derived, exactly as the API will compute it. */
function completionOf(seed: WorkerSeed): number {
  let score = 40; // account + name + phone
  if (seed.headline) score += 10;
  if (seed.bio) score += 10;
  if (seed.skills.length >= 2) score += 10;
  if (seed.languages.length >= 2) score += 5;
  if (seed.verified.profile) score += 10;
  if (seed.verified.documents) score += 15;
  return Math.min(score, 100);
}

export const workers: WorkerProfile[] = WORKER_SEEDS.map((seed) => ({
  id: `wpr_${seed.id}`,
  user: {
    id: `usr_wrk_${seed.id}`,
    name: seed.name,
    // Demo handles follow the same shape the real signup enforces: lowercase, dot separated.
    username: seed.id.replace(/-/g, '.'),
    role: 'WORKER',
    lastActiveAt: minutesAgo(seed.activeMinutesAgo),
  },
  headline: seed.headline,
  bio: seed.bio,
  skills: seed.skills.map(([slug, years, level]) => ({
    skill: skillOf(slug),
    years,
    level,
  })),
  primaryCategory: categoryOf(seed.category),
  experienceYears: seed.experienceYears,
  location: placeOf(seed.city, seed.locality),
  workRadiusKm: seed.radiusKm,
  expectedWage: { amount: seed.wage, type: seed.wageType, negotiable: seed.negotiable },
  availability: seed.availability,
  ...(seed.availableInDays ? { availableFrom: daysAhead(seed.availableInDays) } : {}),
  languages: seed.languages,
  gender: seed.gender,
  ratingAvg: seed.rating,
  ratingCount: seed.ratingCount,
  completedJobs: seed.completedJobs,
  verification: seed.verified,
  profileCompletion: completionOf(seed),
  phone: seed.phoneTail,
  createdAt: daysAgo(120),
  updatedAt: hoursAgo(seed.activeMinutesAgo / 60),
}));

export const workerById: Record<string, WorkerProfile> = Object.fromEntries(
  workers.map((worker) => [worker.id, worker]),
);

export function workerOf(seedId: string): WorkerProfile {
  const worker = workerById[`wpr_${seedId}`];
  if (!worker) throw new Error(`Unknown worker in demo data: ${seedId}`);
  return worker;
}

